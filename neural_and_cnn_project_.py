import gradio as gr
import numpy as np
from PIL import Image
import tensorflow as tf

model = tf.keras.models.load_model("mnist_cnn.keras")

# Make the drawing canvas black
black_canvas = Image.new(
    "RGBA",
    (280, 280),
    (0, 0, 0, 255)
)

def preprocess_image(image_data):
    if image_data is None:
        return None

    composite = image_data.get("composite")

    if composite is None:
        return None

    # Convert to RGBA to handle transparency
    if not isinstance(composite, Image.Image):
        composite = Image.fromarray(
            np.asarray(composite).astype("uint8")
        )

    composite = composite.convert("RGBA")

    # Combine drawing with a black background
    background = Image.new(
        "RGBA",
        composite.size,
        (0, 0, 0, 255)
    )

    image = Image.alpha_composite(
        background, composite
    ).convert("L")

    pixels = np.array(image)

    # Detect drawn white pixels
    mask = pixels > 20

    if not np.any(mask):
        return None

    # Crop the digit
    rows, cols = np.where(mask)

    cropped = image.crop((
        cols.min(),
        rows.min(),
        cols.max() + 1,
        rows.max() + 1
    ))

    # Preserve aspect ratio
    w, h = cropped.size
    scale = 20 / max(w, h)

    new_size = (
        max(1, round(w * scale)),
        max(1, round(h * scale))
    )

    cropped = cropped.resize(
        new_size,
        Image.Resampling.LANCZOS
    )

    # Center on 28 x 28 black background
    final_image = Image.new("L", (28, 28), 0)

    x = (28 - new_size[0]) // 2
    y = (28 - new_size[1]) // 2

    final_image.paste(cropped, (x, y))

    # Normalize like MNIST
    array = np.asarray(
        final_image, dtype=np.float32
    ) / 255.0

    return array.reshape(1, 28, 28, 1)


def predict_digit(image_data):
    processed = preprocess_image(image_data)

    if processed is None:
        raise gr.Error("Please draw a digit first.")

    probabilities = model.predict(
        processed, verbose=0
    )[0]

    return {
        str(i): float(probabilities[i])
        for i in range(10)
    }


with gr.Blocks() as demo:
    gr.Markdown("# Handwritten Digit Recognition")
    gr.Markdown(
        "Draw a white digit from 0 to 9 "
        "on the black canvas."
    )

    sketch = gr.Sketchpad(
        value=black_canvas,
        canvas_size=(280, 280),
        image_mode="RGBA",
        type="pil",
        brush=gr.Brush(
            colors=["#FFFFFF"],
            default_color="#FFFFFF",
            color_mode="fixed"
        )
    )

    output = gr.Label(num_top_classes=3)

    btn = gr.Button("Predict Digit")

    btn.click(
        fn=predict_digit,
        inputs=sketch,
        outputs=output
    )

demo.launch()



